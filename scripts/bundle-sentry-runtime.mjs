#!/usr/bin/env node
/**
 * Bygger workers/sentry-runtime.js från @sentry/cloudflare och kopierar
 * loader + runtime till båda workerkatalogerna. Cloudflare får filerna som
 * extra moduler vid uppladdning (se scripts/cf-worker.mjs).
 *
 *   node scripts/bundle-sentry-runtime.mjs
 */
import { readFileSync, copyFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const version = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).version
const outfile = resolve(root, 'workers/sentry-runtime.js')

await build({
  entryPoints: [resolve(root, 'workers/sentry-runtime-src.js')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  external: ['node:async_hooks', 'cloudflare:workers'],
  banner: { js: '/* Generated by scripts/bundle-sentry-runtime.mjs. Do not edit. */' },
  define: {
    __SENTRY_WORKER_RELEASE__: JSON.stringify(`sds-dashboard@${version}`),
  },
})

const loader = resolve(root, 'workers/sentry-loader.js')
for (const dir of ['workers/sds-cogwork-proxy', 'workers/sodss-signage']) {
  copyFileSync(loader, resolve(root, dir, 'sentry-loader.js'))
  copyFileSync(outfile, resolve(root, dir, 'sentry-runtime.js'))
}

console.log('OK: sentry-runtime.js och sentry-loader.js kopierade till båda workers.')
